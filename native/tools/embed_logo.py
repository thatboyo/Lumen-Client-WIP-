#!/usr/bin/env python3
"""Turns the Lumin ghost mark into client/src/render/logo_data.hpp.

The overlay cannot load files at runtime (it may be injected before the game has
read its assets) and it has no image decoder, so the mark ships inside the DLL as
run-length encoded RGBA. The mark is inverted to light-on-dark and kept opaque-
neutral so the renderer can tint it with the active theme accent.

Usage:
    python3 tools/embed_logo.py <source.png> [height]

Re-run this whenever the logo changes; the generated header is checked in.
"""

import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "client", "src", "render", "logo_data.hpp")

# Rows of the source artwork that hold the mark (the wordmark sits below it).
MARK_TOP, MARK_BOTTOM = 127, 308


def load_mark(path, height):
    image = Image.open(path).convert("RGBA")

    # Crop horizontally to the mark's own alpha bounds so the aspect matches.
    strip = image.crop((0, MARK_TOP, image.width, MARK_BOTTOM))
    bbox = strip.getchannel("A").getbbox()
    if bbox:
        strip = strip.crop(bbox)

    width = max(1, round(strip.width * height / strip.height))
    strip = strip.resize((width, height), Image.LANCZOS)

    pixels = []
    for r, g, b, a in strip.getdata():
        # Invert luminance: the source is a dark ghost with white eyes, which
        # would vanish on the near-black menu. A light mark tinted by the theme
        # accent matches how the mark reads in the design sheet.
        lum = (r * 299 + g * 587 + b * 114) // 1000
        v = 255 - lum
        # 0xAABBGGRR packs to R,G,B,A in memory on little-endian x86, which is
        # the byte order glTexImage2D(GL_RGBA) expects.
        pixels.append((a << 24) | (v << 16) | (v << 8) | v)
    return width, height, pixels


def rle(pixels):
    runs = []
    index = 0
    total = len(pixels)
    while index < total:
        value = pixels[index]
        length = 1
        while index + length < total and pixels[index + length] == value and length < 65535:
            length += 1
        runs.append((length, value))
        index += length
    return runs


def write_header(width, height, runs):
    lines = [
        "// Generated by tools/embed_logo.py from the Lumin ghost mark. Do not edit.",
        "#pragma once",
        "",
        "namespace lumin::logo {",
        "",
        f"constexpr int kWidth = {width};",
        f"constexpr int kHeight = {height};",
        "",
        "// Pairs of (run length, 0xAABBGGRR): straight alpha, light-on-dark so the",
        "// renderer can tint the mark with the active theme accent.",
        f"constexpr unsigned int kRuns[][2] = {{",
    ]

    row = []
    for length, value in runs:
        row.append(f"{{{length},{value}u}}")
        if len(row) == 8:
            lines.append("    " + ",".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ",".join(row) + ",")
    lines.append("};")
    lines.append("")
    lines.append(f"constexpr int kRunCount = {len(runs)};")
    lines.append("")
    lines.append("} // namespace lumin::logo")
    lines.append("")

    with open(OUT, "w", encoding="utf-8") as file:
        file.write("\n".join(lines))

    size = os.path.getsize(OUT)
    print(f"{width}x{height}, {len(runs)} runs, {size} bytes -> {OUT}")


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 1

    height = int(sys.argv[2]) if len(sys.argv) > 2 else 128
    width, height, pixels = load_mark(sys.argv[1], height)
    write_header(width, height, rle(pixels))
    return 0


if __name__ == "__main__":
    sys.exit(main())
